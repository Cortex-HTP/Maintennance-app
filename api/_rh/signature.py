    g = PILImage.open(io.BytesIO(base64.b64decode(SIGNATURE_CACHET_PNG_B64))).convert("L")
    rgba = PILImage.new("RGBA", g.size, (0, 0, 0, 0))
    rgba.putalpha(PILImage.eval(g, lambda v: 255 - v))
    return rgba


